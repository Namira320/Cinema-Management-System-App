    private MovieDTO [] getMovies() {                                                  
        PreparedStatement ps;
        ResultSet rs;
        boolean checkUser = false;
        String query = "SELECT * FROM movie";
        MovieDTO [] movieList = new MovieDTO [10];
        try {
            ps = KoneksiDB.getKoneksi().prepareStatement(query);
            
            rs = ps.executeQuery();
            int i = 0;
            while(rs.next()) {
                MovieDTO moviedto = new MovieDTO();
                moviedto.name = rs.getString("name");
                moviedto.jamTayang = rs.getString("jadwal_tayang");
                movieList[i] = moviedto;
                i++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(Register.class.getName()).log(Level.SEVERE, null, ex);
        }
         return movieList;
    }                                                 

        
    private void jButton_Register_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_Register_ActionPerformed
        String movieName = Jf_nmdepan.getText();
        String jadwalTayang = jf_nmbelakang.getText();

        if(movieName.equals(""))
        {
            JOptionPane.showMessageDialog(null, "Masukkan Movie");
        }

        if(jadwalTayang.equals(""))
        {
            JOptionPane.showMessageDialog(null, "Masukkan JAdwal Tayang");
        }
        else{

            PreparedStatement ps;
            String query = "INSERT INTO movie(name, jadwal_tayang) VALUES (?,?)";

            try {
                ps = KoneksiDB.getKoneksi().prepareStatement(query);
                ps.setString(1, movieName);
                ps.setString(2, jadwalTayang);

                if(ps.executeUpdate() > 0)
                {
                    JOptionPane.showMessageDialog(null, "Movie berhasil ditambah");
                }

            } catch (SQLException ex) {
                System.out.println("Gagal");
            }
        }
    }//GEN-LAST:event_jButton_Register_ActionPerformed

